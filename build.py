"""Inline everything into one file, dist/lab-cpet-tool.html, which works offline. Add the libraries with plain concatenation, so the file stays readable."""
import pathlib
import json
root=pathlib.Path(__file__).parent
# The Word report reuses the styles, fonts and theme of the clinic report template (report/*.xml).
parts={f.name:f.read_text() for f in sorted((root/'report').glob('*.xml'))}
(root/'src/docx_parts.js').write_text('/* Generated by build.py from report/*.xml: style parts of the clinic report template. */\nthis.LabDocxParts = '+json.dumps(parts)+';\n')
h=(root/'index.html').read_text()
h=h.replace('<link rel="stylesheet" href="src/styles.css">','<style>\n'+(root/'src/styles.css').read_text()+'\n</style>')
for src in ['vendor/plotly.min.js','vendor/xlsx.min.js','src/parse.js','src/gdcore.js','src/protocol.js','src/oxynet_models.js','src/oxynet.js','src/lactate.js','src/docx_parts.js','src/docx.js','src/app.js']:
    code=(root/src).read_text().replace('</script','<\\/script')
    h=h.replace(f'<script src="{src}"></script>','<script>\n'+code+'\n</script>')
(root/'dist').mkdir(exist_ok=True); (root/'dist/lab-cpet-tool.html').write_text(h)
print('built',round(len(h)/1e6,2),'MB')
